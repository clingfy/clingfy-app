#!/usr/bin/env python3
"""Generates lib/core/captions/bidi_strong_table.dart from Unicode bidi data.

The caption base direction (first strong character, UAX #9 P2-P3) decides how a
burned-in caption is laid out, so "strong" has to be exactly what the bidi
algorithm says. Two rounds of hand-written ranges each missed real cases (an
emoji variation selector counted as a letter, RLM/LRM ignored, the Bismillah
ligature counted as one), so the table now comes from the data itself.

Regenerate when the Unicode version of Python's unicodedata moves:

    python3 tool/gen_caption_bidi_table.py
"""
import pathlib
import subprocess
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "lib/core/captions/bidi_strong_table.dart"


def ranges(classes):
    out, start = [], None
    for cp in range(0x110000):
        hit = unicodedata.bidirectional(chr(cp)) in classes
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def dart_list(name, rs):
    # One range per line, exempt from the formatter, which would otherwise put
    # every number on its own line and make the table unreadable.
    body = "".join(f"  0x{a:X}, 0x{b:X},\n" for a, b in rs)
    return (
        "// dart format off\n"
        f"const List<int> {name} = <int>[\n{body}];\n"
        "// dart format on\n"
    )


MIN_UNICODE = (16, 0, 0)


def main():
    # An older interpreter has older bidi data and would silently drop letters
    # added since, with every test still passing. macOS's system python3 3.9
    # ships Unicode 13. Refuse rather than regress.
    version = tuple(int(p) for p in unicodedata.unidata_version.split("."))
    if version < MIN_UNICODE:
        raise SystemExit(
            f"unicodedata is {unicodedata.unidata_version}; need >= "
            f"{'.'.join(map(str, MIN_UNICODE))}. Use a newer python3."
        )
    ltr = ranges({"L"})
    rtl = ranges({"R", "AL"})
    text = (
        "// GENERATED by tool/gen_caption_bidi_table.py from Unicode "
        f"{unicodedata.unidata_version} bidi data. Do not edit by hand.\n"
        "//\n"
        "// Inclusive [start, end] code-point pairs, sorted and non-overlapping.\n"
        "// `kBidiStrongLtr` is bidi class L; `kBidiStrongRtl` is classes R and AL.\n"
        "// Everything else (digits, punctuation, marks, emoji, controls) is not\n"
        "// strong and never decides a paragraph's direction.\n\n"
        f"const String kBidiUnicodeVersion = '{unicodedata.unidata_version}';\n\n"
        + dart_list("kBidiStrongLtr", ltr)
        + "\n"
        + dart_list("kBidiStrongRtl", rtl)
    )
    OUT.write_text(text, encoding="utf-8")
    subprocess.run(["dart", "format", str(OUT)], check=True, capture_output=True)
    print(f"wrote {OUT.name}: {len(ltr)} L ranges, {len(rtl)} R/AL ranges")


if __name__ == "__main__":
    main()
